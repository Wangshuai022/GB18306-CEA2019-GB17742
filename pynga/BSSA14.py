    def ftype(self):
        FT = rake2ftype_BA(self.rake)  # change in this version
        if FT not in self.fault:
            print("Invalid fault type!")
            print("It should be in one of the following list:")
            print(self.fault)
            raise ValueError
        else:
            if FT == "unspecified" or FT == "U":
                self.U = 1
            else:
                self.U = 0
            if FT == "strike-slip" or FT == "SS":
                self.SS = 1
            else:
                self.SS = 0
            if FT == "normal" or FT == "NM":
                self.NM = 1
            else:
                self.NM = 0
            if FT == "reverse" or FT == "RV":
                self.RV = 1
            else:
                self.RV = 0
        return FT

    def moment_function(self, Tother=None):
        """
        Magnitude-Moment scaling
        """
        if Tother != None:
            Ti = GetKey(Tother)
        else:
            Ti = GetKey(self.T)

        e0 = self.Coefs[str(Ti)]["e0"]
        e1 = self.Coefs[str(Ti)]["e1"]
        e2 = self.Coefs[str(Ti)]["e2"]
        e3 = self.Coefs[str(Ti)]["e3"]
        e4 = self.Coefs[str(Ti)]["e4"]
        e5 = self.Coefs[str(Ti)]["e5"]
        e6 = self.Coefs[str(Ti)]["e6"]
        Mh = self.Coefs[str(Ti)]["Mh"]

        faulting = e0 * self.U + e1 * self.SS + e2 * self.NM + e3 * self.RV
        if self.M <= Mh:
            term = faulting + e4 * (self.M - Mh) + e5 * (self.M - Mh) ** 2
        else:
            term = faulting + e6 * (self.M - Mh)
        # print 'f_e: ', term
        return term

    def distance_function(self, Tother=None):
        """
        Distance function
        Geometrical spreading? (yes ~ ln(R))
        """
        if Tother != None:
            Ti = GetKey(Tother)
        else:
            Ti = GetKey(self.T)

        h = self.Coefs[Ti]["h"]
        c1 = self.Coefs[Ti]["c1"]
        c2 = self.Coefs[Ti]["c2"]
        c3 = self.Coefs[Ti]["c3"]
        D_c3 = self.Coefs[Ti]["D_c3_%s" % self.region]

        R = np.sqrt(self.Rjb**2 + h**2)
        term = (
            (c1 + c2 * (self.M - self.Mref)) * np.log(R / self.Rref)
            + c3 * (R - self.Rref)
            + D_c3 * (R - self.Rref)
        )
        # print 'Rtmp: ', R, ', Dc3: ', D_c3
        # print 'f_PB: ', term
        return term

    def Vs30toZ1pt0(self, Vs30):
        # output is in km which will be used in the model (make sure your input is in meter)
        if self.country in ["California", "CA"]:
            return (-7.15 / 4.0) * np.log((Vs30**4 + 570.94**4) / (1360**4 + 570.94**4))
        elif self.country in ["Japan", "JA"]:
            return (-5.23 / 2.0) * np.log((Vs30**2 + 412.39**2) / (1360**2 + 412.39**2))
        else:
            return (-7.15 / 4.0) * np.log((Vs30**4 + 570.94**4) / (1360**4 + 570.94**4))

    def soil_function(self, Vs30=None, Tother=None):
        """
        Site Amplification Function
        """
        if Vs30 != None:
            self.Vs30 = Vs30
        if Tother != None:
            Ti = GetKey(Tother)
            T = Tother
        else:
            Ti = GetKey(self.T)
            T = self.T

        # ===============
        # linear term
        # ===============
        c = self.Coefs[Ti]["c"]
        Vc = self.Coefs[Ti]["Vc"]
        if self.Vs30 <= Vc:
            flin = c * np.log(self.Vs30 / self.Vref)
        else:
            flin = c * np.log(Vc / self.Vref)

        # =================
        # non-linear term
        # =================

        # 1. compute pga4nl, which is defined as the media PGA when
        # Vs30=Vref=760 m/s
        Tpga = -1.0  # compute PGA
        pga4nl = np.exp(self.moment_function(Tother=Tpga) + self.distance_function(Tother=Tpga))
        # print 'PGAr: ', pga4nl

        # 2. compute nonlinear site effect
        f4 = self.Coefs[Ti]["f4"]
        f5 = self.Coefs[Ti]["f5"]
        f2 = f4 * (np.exp(f5 * (min([self.Vs30, 760]) - 360)) - np.exp(f5 * (760 - 360)))
        fnl = self.f1 + f2 * np.log((pga4nl + self.f3) / self.f3)

        self.Fsite = flin + fnl

        # consider the correction due to basin apparence (big changes!!!)
        if self.Z10 == None:
            dZ1pt0 = 0.0
            fdZ1 = 0.0  # no consideration of basin effects
        else:
            f6 = self.Coefs[Ti]["f6"]
            f7 = self.Coefs[Ti]["f7"]
            Z1pt0_Vs30 = np.exp(self.Vs30toZ1pt0(self.Vs30)) / 1000.0
            dZ1pt0 = self.Z10 - Z1pt0_Vs30
            #  print 'dz10: ', dZ1pt0
            if T < 0.65:
                fdZ1 = 0.0
            else:
                # print 'f6, f7:', f6, f7
                if dZ1pt0 <= f7 / f6:
                    fdZ1 = f6 * dZ1pt0
                else:
                    fdZ1 = f7
        # print "self.Fsite, fdZ1: ", self.Fsite, fdZ1
        return self.Fsite + fdZ1

    def site_function_BSSA14(
        self, PGAr, Vref, Vs30=None, Tother=None, Z10=None, Region_name="Japan"
    ):
        """
        Site Amplification Function
        PGAr  参考场地PGA (g)  Vref=760m/s位置
        Vref  参考场地Vs30  一般来说是760m/s，我们可以自己调整试试效果
        Vs30  场地Vs30  m/s
        Tother   周期点 0.1-10s
        Z10   Z1.0深度， km
        Region_name  区域名称  Japan  JA  CA  California
        """
        # 场地矫正周期点
        Ti = f"{Tother:.3f}"
        # Vref = 760  # m/s

        # ===============
        # linear term
        # ===============
        c = self.Coefs[Ti]["c"]
        Vc = self.Coefs[Ti]["Vc"]
        if Vs30 <= Vc:
            flin = c * np.log(Vs30 / Vref)
        else:
            flin = c * np.log(Vc / Vref)

        # =================
        # non-linear term
        # =================

        # 1. compute PGAr, PGAr的单位是 g 千万注意！！！
        PGAr = PGAr * 1

        # 2. compute nonlinear site effect
        f4 = self.Coefs[Ti]["f4"]
        f5 = self.Coefs[Ti]["f5"]
        f2 = f4 * (np.exp(f5 * (min([Vs30, Vref]) - 360)) - np.exp(f5 * (Vref - 360)))
        fnl = self.f1 + f2 * np.log((PGAr + self.f3) / self.f3)

        Fsite = flin + fnl

        # consider the correction due to basin apparence (big changes!!!)
        # 如果Z10未知，则不考虑盆地项
        if Z10 == None:
            dZ1pt0 = 0.0
            fdZ1 = 0.0  # no consideration of basin effects
        else:
            # 如果Z10已知，则
            f6 = self.Coefs[Ti]["f6"]
            f7 = self.Coefs[Ti]["f7"]

            # 计算μz10
            if Region_name in ["Japan", "JA"]:
                Z1pt0_Vs30 = (
                    np.exp((-5.23 / 2.0) * np.log((Vs30**2 + 412.39**2) / (1360**2 + 412.39**2)))
                    / 1000
                )
            else:
                Z1pt0_Vs30 = (
                    np.exp((-7.15 / 4.0) * np.log((Vs30**4 + 570.94**4) / (1360**4 + 570.94**4)))
                    / 1000.0
                )

            dZ1pt0 = Z10 - Z1pt0_Vs30
            # 盆地项判别：如果周期小于0.65，则没有盆地项，否则，依次考虑为f6  f7之类
            # 详细见BSSA14 文章 公式9
            if Tother < 0.65:
                fdZ1 = 0.0
            else:
                if dZ1pt0 <= f7 / f6:
                    fdZ1 = f6 * dZ1pt0
                else:
                    fdZ1 = f7
        # print "self.Fsite, fdZ1: ", self.Fsite, fdZ1
        return Fsite + fdZ1

    def compute_im(self, terms=(1, 1, 1)):
        """
        Compute IM based on functional form of BA08 model
        """
        IM = np.exp(
            terms[0] * self.moment_function()
            + terms[1] * self.distance_function()
            + terms[2] * self.soil_function()
        )
        # note: for PGA and PSA, IM has unit (g) here
        #       for PGV, IM has unit (cm/s) !  (after np.exp)
        # print 'IM: ', IM
        # print '====================================='
        return IM

    def compute_std(self):
        Ti = GetKey(self.T)

        phi1 = self.Coefs[str(Ti)]["phi1"]
        phi2 = self.Coefs[str(Ti)]["phi2"]
        tau1 = self.Coefs[str(Ti)]["tau1"]
        tau2 = self.Coefs[str(Ti)]["tau2"]
        R1 = self.Coefs[str(Ti)]["R1"]
        R2 = self.Coefs[str(Ti)]["R2"]
        V1 = self.Coefs[str(Ti)]["V1"]
        V2 = self.Coefs[str(Ti)]["V2"]
        D_phi_R = self.Coefs[str(Ti)]["D_phi_R"]
        D_phi_V = self.Coefs[str(Ti)]["D_phi_V"]

        # compute intra-event sigma
        if self.M <= 4.5:
            phiM = phi1
        elif 4.5 < self.M <= 5.5:
            phiM = phi1 + (phi2 - phi1) * (self.M - 4.5)
        else:
            phiM = phi2

        if self.Rjb <= R1:
            phiMR = phiM
        elif R1 < self.Rjb <= R2:
            phiMR = phiM + D_phi_R * (np.log(self.Rjb / R1) / np.log(R2 / R1))
        else:
            phiMR = phiM + D_phi_R

        if self.Vs30 >= V2:
            sigma = phiMR
        elif V1 <= self.Vs30 < V2:
            sigma = phiMR - D_phi_V * (np.log(V2 * 1.0 / self.Vs30) / np.log(V2 * 1.0 / V1))
        else:
            sigma = phiMR - D_phi_V

        # compute inter-event
        if self.M <= 4.5:
            tau = tau1
        elif 4.5 < self.M <= 5.5:
            tau = tau1 + (tau2 - tau1) * (self.M - 4.5)
        else:
            tau = tau2
        sigmaT = np.sqrt(sigma**2 + tau**2)

        return sigmaT, tau, sigma


