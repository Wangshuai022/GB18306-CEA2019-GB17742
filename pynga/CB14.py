    def moment_function(self, Tother=None):
        """
        Moment term
        """
        if Tother != None:
            Ti = GetKey(Tother)
        else:
            Ti = GetKey(self.T)

        c0 = self.Coefs[Ti]["c0"]
        c1 = self.Coefs[Ti]["c1"]
        c2 = self.Coefs[Ti]["c2"]
        c3 = self.Coefs[Ti]["c3"]
        c4 = self.Coefs[Ti]["c4"]

        if self.M <= 4.5:
            f_mag = c0 + c1 * self.M
        elif 4.5 < self.M <= 5.5:
            f_mag = c0 + c1 * self.M + c2 * (self.M - 4.5)
        elif 5.5 < self.M <= 6.5:
            f_mag = (
                c0 + c1 * self.M + c2 * (self.M - 4.5) + c3 * (self.M - 5.5)
            )
        else:
            f_mag = (
                c0
                + c1 * self.M
                + c2 * (self.M - 4.5)
                + c3 * (self.M - 5.5)
                + c4 * (self.M - 6.5)
            )
        # print 'f_mag:',f_mag
        return f_mag

    def distance_function(self, Tother=None):
        """
        Geometrical attenuation
        """
        if Tother != None:
            Ti = GetKey(Tother)
        else:
            Ti = GetKey(self.T)

        c5 = self.Coefs[Ti]["c5"]
        c6 = self.Coefs[Ti]["c6"]
        c7 = self.Coefs[Ti]["c7"]

        Rtmp = np.sqrt(self.Rrup**2 + c7**2)
        f_dis = (c5 + c6 * self.M) * np.log(Rtmp)
        # print 'f_dis:', f_dis
        return f_dis

    def attenuation_function(self, Tother=None):
        """
        Anelastic Attneuation
        """
        if Tother != None:
            Ti = GetKey(Tother)
        else:
            Ti = GetKey(self.T)
        c20 = self.Coefs[Ti]["c20"]
        D_c20 = self.Coefs[Ti]["D_c20_%s" % self.region]
        if self.Rrup > 80:
            f_atn = (c20 + D_c20) * (self.Rrup - 80)
        else:
            f_atn = 0.0
        # print 'f_atn:', f_atn
        return f_atn

    def fault_function(self, Tother=None):
        """
        Fault mechanism term
        or style of the fault
        """
        if Tother != None:
            Ti = GetKey(Tother)
        else:
            Ti = GetKey(self.T)
        c8 = self.Coefs[Ti]["c8"]
        c9 = self.Coefs[Ti]["c9"]
        f_fltF = c8 * self.Frv + c9 * self.Fnm
        f_fltM = (
            0 * (self.M <= 4.5)
            + (self.M - 4.5) * (4.5 < self.M <= 5.5)
            + 1 * (self.M > 5.5)
        )
        f_flt = f_fltF * f_fltM
        # print 'f_flt:', f_flt
        return f_flt

    def hw_function(self, Tother=None):
        """
        Hanging Wall term
        """
        if Tother != None:
            Ti = GetKey(Tother)
        else:
            Ti = GetKey(self.T)

        c10 = self.Coefs[Ti]["c10"]
        a2 = self.Coefs[Ti]["a2"]
        h1 = self.Coefs[Ti]["h1"]
        h2 = self.Coefs[Ti]["h2"]
        h3 = self.Coefs[Ti]["h3"]
        h4 = self.Coefs[Ti]["h4"]
        h5 = self.Coefs[Ti]["h5"]
        h6 = self.Coefs[Ti]["h6"]

        # print 'Rx:', self.Rx
        R1 = self.W * np.cos(self.dip * np.pi / 180.0)
        R2 = 62 * self.M - 350
        tmp1 = self.Rx / R1
        tmp2 = (self.Rx - R1) / (R2 - R1)
        f1_Rx = h1 + h2 * tmp1 + h3 * (tmp1) ** 2
        f2_Rx = h4 + h5 * tmp2 + h6 * (tmp2) ** 2
        f_hngRx = (
            0 * (self.Rx < 0)
            + f1_Rx * (0.0 <= self.Rx < R1)
            + max([f2_Rx, 0.0]) * (self.Rx >= R1)
        )

        f_hngRrup = 1 * (self.Rrup == 0) + (
            self.Rrup - self.Rjb
        ) / self.Rrup * (self.Rrup > 0)
        f_hngM = (
            0 * (self.M <= 5.5)
            + ((self.M - 5.5) * (1 + a2 * (self.M - 6.5)))
            * (5.5 < self.M <= 6.5)
            + (1 + a2 * (self.M - 6.5)) * (self.M > 6.5)
        )
        f_hngZ = (1 - 0.06 * self.Ztor) * (self.Ztor <= 16.66) + 0 * (
            self.Ztor > 16.66
        )
        f_hngD = (90 - self.dip) / 45.0
        f_hng = c10 * f_hngRx * f_hngRrup * f_hngM * f_hngZ * f_hngD * self.Fhw
        # print 'f_hng: ', f_hng
        return f_hng

    def rup_dip_function(self, Tother=None):
        if Tother != None:
            Ti = GetKey(Tother)
        else:
            Ti = GetKey(self.T)
        c19 = self.Coefs[Ti]["c19"]
        f_dip = (
            c19 * self.dip * (self.M <= 4.5)
            + c19 * (5.5 - self.M) * self.dip * (4.5 < self.M <= 5.5)
            + 0 * (self.M > 5.5)
        )
        # print 'f_dip:', f_dip
        return f_dip

    def hypo_depth_function(self, Tother=None):
        if Tother != None:
            Ti = GetKey(Tother)
        else:
            Ti = GetKey(self.T)

        c17 = self.Coefs[Ti]["c17"]
        c18 = self.Coefs[Ti]["c18"]
        f_hypoH = (
            0 * (self.Zhypo <= 7)
            + (self.Zhypo - 7) * (7 < self.Zhypo <= 20)
            + 13 * (self.Zhypo > 20)
        )
        f_hypoM = (
            c17 * (self.M <= 5.5)
            + (c17 + (c18 - c17) * (self.M - 5.5)) * (5.5 < self.M <= 6.5)
            + c18 * (self.M > 6.5)
        )
        f_hyp = f_hypoH * f_hypoM
        # print 'f_hyp:',f_hyp
        return f_hyp

    def basin_function(self, Tother=None, Z25=None):
        """
        Basin-effect term
        """
        if Tother != None:
            Ti = GetKey(Tother)
        else:
            Ti = GetKey(self.T)
        if Z25 == None:
            Z25 = self.Z25
        # print("衰减关系--CB14,Z25:", Z25)

        c14 = self.Coefs[Ti]["c14"]
        c15 = self.Coefs[Ti]["c15"]
        c16 = self.Coefs[Ti]["c16"]
        k3 = self.Coefs[Ti]["k3"]
        if Z25 <= 1.0:
            f_sed = (c14 + c15 * self.SJ) * (Z25 - 1.0)
        elif 1.0 < Z25 <= 3.0:
            f_sed = 0.0
        else:
            f_sed = (
                c16 * k3 * np.exp(-0.75) * (1 - np.exp(-0.25 * (Z25 - 3.0)))
            )
        # print 'f_sed:', f_sed
        return f_sed

    def A1100_calc(self):
        Tother = -1.0
        A1100 = np.exp(
            self.moment_function(Tother=Tother)
            + self.distance_function(Tother=Tother)
            + self.attenuation_function(Tother=Tother)
            + self.fault_function(Tother=Tother)
            + self.hw_function(Tother=Tother)
            + self.rup_dip_function(Tother=Tother)
            + self.hypo_depth_function(Tother=Tother)
            + self.basin_function(
                Tother=Tother,
                Z25=0.3975,
            )
            + self.site_function(A1100=0, Vs30=1100.0, Tother=Tother)
        )
        # print("PGA1100:", A1100)
        # print '=================================='
        return A1100

    def site_function(self, A1100=None, Vs30=None, Tother=None):
        """
        Shallow site effect term
        Be careful to the input variables (they are keys, not arguments)
        """

        # PGA at reference rock that has Vs30 = 1100 (unit: m/s)
        if A1100 == None:
            A1100 = self.A1100_calc()

        if Vs30 == None:
            Vs30 = self.Vs30

        if Tother != None:
            Ti = GetKey(Tother)
        else:
            Ti = GetKey(self.T)

        c11 = self.Coefs[Ti]["c11"]
        c12 = self.Coefs[Ti]["c12"]
        c13 = self.Coefs[Ti]["c13"]
        k1 = self.Coefs[Ti]["k1"]
        k2 = self.Coefs[Ti]["k2"]

        if Vs30 <= k1:
            f_siteG = c11 * np.log(Vs30 / k1) + k2 * (
                np.log(A1100 + self.c * (Vs30 / k1) ** self.n)
                - np.log(A1100 + self.c)
            )
        else:
            f_siteG = (c11 + k2 * self.n) * np.log(Vs30 / k1)

        if Vs30 <= 200:
            f_siteJ = (c12 + k2 * self.n) * (
                np.log(Vs30 / k1) - np.log(200.0 / k1)
            )
        else:
            f_siteJ = (c13 + k2 * self.n) * np.log(Vs30 / k1)

        f_site = f_siteG + self.SJ * f_siteJ
        # print 'f_site:', f_site
        return f_site

